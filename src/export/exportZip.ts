import JSZip from 'jszip';
import type { CreativeProject } from '../model/types';
import { generateHtml } from './generateHtml';

const EXT: Record<string, string> = {
  'image/png': 'png',
  'image/jpeg': 'jpg',
  'image/jpg': 'jpg',
  'image/gif': 'gif',
  'image/webp': 'webp',
  'image/svg+xml': 'svg',
};

function dataUrlToBytes(dataUrl: string): Uint8Array | null {
  const m = /^data:([^;,]+);base64,(.*)$/s.exec(dataUrl);
  if (!m) return null;
  const bin = atob(m[2]);
  const bytes = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);
  return bytes;
}

/**
 * Build a ZIP containing the standalone creative:
 * index.html + imgs/* for locally uploaded assets.
 */
export async function buildCreativeZip(project: CreativeProject): Promise<Blob> {
  const zip = new JSZip();
  const imgDir = zip.folder('imgs');

  // map assetId -> zip-relative path; remote assets keep their URL
  const pathById = new Map<string, string>();
  for (const a of project.assets) {
    if (a.kind !== 'image') continue;
    if (a.src.startsWith('data:')) {
      const ext = EXT[a.mimeType] ?? 'png';
      const safeName = a.name.replace(/[^\w.-]+/g, '_').slice(0, 60) || a.id;
      const path = `imgs/${a.id}_${safeName}.${ext}`;
      const bytes = dataUrlToBytes(a.src);
      if (bytes && imgDir) {
        zip.file(path, bytes);
        pathById.set(a.id, `./${path}`);
      }
    } else if (/^https?:\/\//i.test(a.src)) {
      pathById.set(a.id, a.src);
    }
  }

  const assetUrl = (id: string | undefined): string =>
    (id && pathById.get(id)) || '';

  const html = generateHtml(project, assetUrl);
  zip.file('index.html', html);

  const remoteCount = project.assets.filter(
    (a) => a.kind === 'image' && !a.src.startsWith('data:'),
  ).length;
  const totalBytes = [...pathById.keys()].length;
  zip.file(
    'README.txt',
    [
      `${project.name} — HTML5 creative`,
      `Dimensions: ${project.artboard.width}x${project.artboard.height}`,
      `Generated by AdPilot Studio`,
      ``,
      `Files:`,
      `  index.html   self-contained creative (markup + styles + runtime)`,
      `  imgs/        ${totalBytes} local image asset(s)`,
      remoteCount ? `  note: ${remoteCount} asset(s) are remote URLs (not bundled)` : '',
      ``,
      `Click-through: var clickTag is defined in index.html.`,
      `Ad-server note: platform requirements (file weight, SSL, meta tags)`,
      `still need verification for your target network.`,
    ].filter(Boolean).join('\n'),
  );

  return zip.generateAsync({ type: 'blob' });
}

export function downloadBlob(blob: Blob, filename: string) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 5000);
}
